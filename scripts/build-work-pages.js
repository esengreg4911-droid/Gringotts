// Regenerate entry pages after editing index.html or adding catalog titles.
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const createWorkRoutes=require('../work-routes.js');
const root=path.resolve(__dirname,'..'),context={window:{}};
vm.runInNewContext(fs.readFileSync(path.join(root,'data.js'),'utf8'),context);
const data=context.window.DATA,routes=createWorkRoutes(data);
const template=fs.readFileSync(path.join(root,'index.html'),'utf8');
const marker='<!-- Generated by scripts/build-work-pages.js -->';
const escape=s=>s.replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
const pages=data.map(work=>{
 const slug=routes.byId[work.id],dir=path.join(root,slug),file=path.join(dir,'index.html');
 if(fs.existsSync(dir)&&(!fs.existsSync(file)||!fs.readFileSync(file,'utf8').includes(marker)))throw new Error('Existing directory is not a generated work page: '+slug);
 const html=template.replace('<head>','<head>\n'+marker+'\n<base href="../">').replace('<title>GRINGOTTS</title>','<title>'+escape(work.zh||work.title)+' · GRINGOTTS</title>');
 return {dir,file,html};
});
for(const page of pages){fs.mkdirSync(page.dir,{recursive:true});fs.writeFileSync(page.file,page.html);}
console.log('Generated '+pages.length+' work entry pages.');
